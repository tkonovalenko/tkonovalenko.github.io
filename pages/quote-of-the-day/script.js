let insertHTML = () => {
    const randIndex = Math.floor(Math.random() * quotes.length)
    const randQuote = quotes[randIndex];
    localStorage.setItem('randQuote', JSON.stringify(randQuote));
    document.querySelector('.quote').innerHTML
        = `<blockquote class="quote__text">${randQuote['quote']}<div class="quote__author">~ ${randQuote['name']}</div></blockquote>`;
}

let getQuote = () => {
    let oldQuoteTime = localStorage.getItem('quoteTime');
    if (oldQuoteTime === null) {
        oldQuoteTime = Date.now();
        localStorage.setItem('quoteTime', oldQuoteTime);
        insertHTML();
    }
    else {
        let oldQuoteDays = Math.floor(oldQuoteTime / (1000 * 60 * 60 * 24));
        let newQuoteTime = new Date();
        newQuoteTime = newQuoteTime.getTime();

        if (Math.floor(newQuoteTime / (1000 * 60 * 60 * 24)) > oldQuoteDays) {
            insertHTML();
            localStorage.setItem('quoteTime', newQuoteTime);
        }
    }

}

let initPrevQuote = () => {
    let randQuote = localStorage.getItem('randQuote');
    if (randQuote !== null) {
        randQuote = JSON.parse(randQuote);
        document.querySelector('.quote').innerHTML
            = `<blockquote class="quote__text">${randQuote['quote']}<div class="quote__author">~ ${randQuote['name']}</div></blockquote>`;
    }
}
